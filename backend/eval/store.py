"""Where evaluation data lives, and how labels are read and written.

    eval/samples/                 committed: generated sample resumes + labels.json
    eval/private/resumes/         real resumes you add (gitignored)
    eval/private/labels/          one parser label per real resume (gitignored)
    eval/private/relevance/       pool.json (what to judge) and labels.json (judgments)
    eval/private/cache/           cached parses, so reports don't re-spend LLM calls

Documents are addressed as "sample:<file>" or "private:<file>".
"""

import json
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from app.parsing.schema import Seniority

ROOT = Path(__file__).parent
SAMPLES = ROOT / "samples"
PRIVATE = ROOT / "private"
PRIVATE_RESUMES = PRIVATE / "resumes"
PRIVATE_LABELS = PRIVATE / "labels"
RELEVANCE = PRIVATE / "relevance"
CACHE = PRIVATE / "cache"
RESUME_SUFFIXES = {".pdf", ".docx"}

Origin = Literal["sample", "private"]
Status = Literal["none", "draft", "verified"]


class LabelRole(BaseModel):
    title: str
    company: str
    start: str | None = None  # "YYYY-MM", "YYYY"
    end: str | None = None  # "YYYY-MM", "YYYY" or "present"


class LabelEducation(BaseModel):
    institution: str
    degree: str | None = None
    field: str | None = None
    year: str | None = None


class ParserLabel(BaseModel):
    """The truth for one resume, written (or corrected) by a person."""

    file: str
    seniority: Seniority | None = None
    roles: list[LabelRole] = Field(default_factory=list)
    education: list[LabelEducation] = Field(default_factory=list)
    skills: list[str] = Field(default_factory=list)
    notes: str = ""
    verified: bool = False  # only verified labels count in reports


class Document(BaseModel):
    id: str
    origin: Origin
    file: str
    status: Status


def _sample_labels() -> dict[str, ParserLabel]:
    raw = json.loads((SAMPLES / "labels.json").read_text())
    return {item["file"]: ParserLabel.model_validate({**item, "verified": True}) for item in raw}


def document_path(doc_id: str) -> Path:
    origin, _, name = doc_id.partition(":")
    folder = {"sample": SAMPLES, "private": PRIVATE_RESUMES}.get(origin)
    if folder is None or not name or "/" in name or "\\" in name or name.startswith("."):
        raise KeyError(doc_id)
    path = folder / name
    if path.suffix.lower() not in RESUME_SUFFIXES or not path.is_file():
        raise KeyError(doc_id)
    return path


def _label_path(name: str) -> Path:
    return PRIVATE_LABELS / f"{name}.json"


def load_label(doc_id: str) -> ParserLabel | None:
    origin, _, name = doc_id.partition(":")
    if origin == "sample":
        return _sample_labels().get(name)
    path = _label_path(name)
    return ParserLabel.model_validate_json(path.read_text()) if path.is_file() else None


def save_label(doc_id: str, label: ParserLabel) -> None:
    origin, _, name = doc_id.partition(":")
    if origin != "private":
        raise PermissionError("sample labels are generated by eval/make_samples.py")
    document_path(doc_id)  # must exist
    PRIVATE_LABELS.mkdir(parents=True, exist_ok=True)
    _label_path(name).write_text(label.model_copy(update={"file": name}).model_dump_json(indent=2))


def list_documents() -> list[Document]:
    docs = []
    for name, label in sorted(_sample_labels().items()):
        if (SAMPLES / name).is_file():
            docs.append(Document(id=f"sample:{name}", origin="sample", file=name,
                                 status="verified" if label.verified else "draft"))  # fmt: skip
    if PRIVATE_RESUMES.is_dir():
        for path in sorted(PRIVATE_RESUMES.iterdir()):
            if path.suffix.lower() not in RESUME_SUFFIXES:
                continue
            label = load_label(f"private:{path.name}")
            status: Status = (
                "none" if label is None else ("verified" if label.verified else "draft")
            )
            docs.append(
                Document(id=f"private:{path.name}", origin="private", file=path.name, status=status)
            )
    return docs


def verified_labels() -> dict[str, ParserLabel]:
    """doc id -> label, for every document whose label a person has verified."""
    out = {}
    for doc in list_documents():
        if doc.status == "verified":
            label = load_label(doc.id)
            assert label is not None
            out[doc.id] = label
    return out


# ── relevance ─────────────────────────────────────────────────────────────────────

Grade = Literal[0, 1, 2]  # 0 not a fit, 1 partly, 2 good fit


def load_pool() -> dict | None:
    path = RELEVANCE / "pool.json"
    return json.loads(path.read_text()) if path.is_file() else None


def save_pool(pool: dict) -> None:
    RELEVANCE.mkdir(parents=True, exist_ok=True)
    (RELEVANCE / "pool.json").write_text(json.dumps(pool, indent=1))


def load_judgments() -> dict[str, dict[str, int]]:
    path = RELEVANCE / "labels.json"
    return json.loads(path.read_text()) if path.is_file() else {}


def save_judgment(resume_key: str, job_id: int, grade: int | None) -> None:
    judgments = load_judgments()
    by_job = judgments.setdefault(resume_key, {})
    if grade is None:
        by_job.pop(str(job_id), None)
    else:
        by_job[str(job_id)] = grade
    RELEVANCE.mkdir(parents=True, exist_ok=True)
    (RELEVANCE / "labels.json").write_text(json.dumps(judgments, indent=1, sort_keys=True))
