"use client";

import Link from "next/link";
import { use, useEffect, useState } from "react";

import { errorMessage, type Seniority } from "@/lib/api";
import {
  evalApi,
  toolsDisabled,
  type DocumentDetail,
  type LabelEducation,
  type LabelRole,
  type ParserLabel,
} from "@/lib/evalApi";

const LEVELS: Seniority[] = ["intern", "junior", "mid", "senior", "lead"];
const DATE = /^(present|\d{4}(-(0[1-9]|1[0-2]))?)$/;

const input =
  "w-full rounded border border-zinc-300 bg-white px-2 py-1 text-sm dark:border-zinc-700 dark:bg-zinc-900";

function emptyLabel(file: string): ParserLabel {
  return { file, seniority: null, roles: [], education: [], skills: [], notes: "", verified: false };
}

function DateInput({ value, onChange, label }: { value: string | null; onChange: (v: string | null) => void; label: string }) {
  const bad = value !== null && value !== "" && !DATE.test(value);
  return (
    <input
      aria-label={label}
      value={value ?? ""}
      onChange={(e) => onChange(e.target.value.trim() || null)}
      placeholder="YYYY-MM"
      className={`${input} ${bad ? "border-red-500 dark:border-red-500" : ""}`}
      title="YYYY-MM, YYYY, or present"
    />
  );
}

export function ResumeLabeler({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const query = use(searchParams);
  const id = typeof query.id === "string" ? query.id : "";
  const [detail, setDetail] = useState<DocumentDetail | null>(null);
  const [label, setLabel] = useState<ParserLabel | null>(null);
  const [skillsText, setSkillsText] = useState("");
  const [busy, setBusy] = useState<"draft" | "save" | null>(null);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    evalApi.document(id).then(
      (d) => {
        if (cancelled) return;
        setDetail(d);
        const initial = d.label ?? emptyLabel(d.document.file);
        setLabel(initial);
        setSkillsText(initial.skills.join(", "));
      },
      (err: unknown) => {
        if (!cancelled)
          setError(toolsDisabled(err) ? "Document not found, or the labeling tools are off." : errorMessage(err));
      },
    );
    return () => {
      cancelled = true;
    };
  }, [id]);

  if (error) return <p role="alert" className="text-sm text-red-700 dark:text-red-400">{error}</p>;
  if (!detail || !label) return <p className="text-sm text-zinc-500">Loading…</p>;

  const readOnly = detail.document.origin === "sample";
  const update = (patch: Partial<ParserLabel>) => setLabel({ ...label, ...patch });
  const setRole = (i: number, patch: Partial<LabelRole>) =>
    update({ roles: label.roles.map((r, j) => (j === i ? { ...r, ...patch } : r)) });
  const setSchool = (i: number, patch: Partial<LabelEducation>) =>
    update({ education: label.education.map((e, j) => (j === i ? { ...e, ...patch } : e)) });
  const badDates = label.roles.some((r) => [r.start, r.end].some((d) => d && !DATE.test(d)));

  async function prefill() {
    setBusy("draft");
    setMessage(null);
    try {
      const draft = await evalApi.draft(id);
      setLabel({ ...draft, notes: label?.notes ?? "" });
      setSkillsText(draft.skills.join(", "));
      setMessage("Filled from the parser. Check every field against the resume before verifying.");
    } catch (err) {
      setMessage(errorMessage(err));
    } finally {
      setBusy(null);
    }
  }

  async function save(verified: boolean) {
    if (!label) return;
    setBusy("save");
    setMessage(null);
    const skills = skillsText.split(/[,\n]/).map((s) => s.trim()).filter(Boolean);
    try {
      const saved = await evalApi.save(id, { ...label, skills, verified });
      setLabel(saved);
      setMessage(verified ? "Saved as verified." : "Draft saved.");
    } catch (err) {
      setMessage(errorMessage(err));
    } finally {
      setBusy(null);
    }
  }

  return (
    <div className="space-y-4">
      <header className="space-y-1">
        <Link href="/label" className="text-sm text-zinc-500 hover:underline">← All documents</Link>
        <h1 className="text-xl font-semibold">{detail.document.file}</h1>
        {readOnly && (
          <p className="text-sm text-zinc-500">
            Sample labels are generated by <code>eval/make_samples.py</code>; read-only here.
          </p>
        )}
      </header>

      <div className="grid gap-4 lg:grid-cols-2">
        <pre className="max-h-[75vh] overflow-auto whitespace-pre-wrap rounded-lg border border-zinc-200 bg-white p-3 text-xs leading-relaxed dark:border-zinc-800 dark:bg-zinc-900">
          {detail.text}
        </pre>

        <fieldset disabled={readOnly || busy !== null} className="space-y-5 text-sm">
          {!readOnly && (
            <button type="button" onClick={prefill} className="rounded-md border border-zinc-300 px-3 py-1.5 font-medium hover:bg-zinc-100 dark:border-zinc-700 dark:hover:bg-zinc-800">
              {busy === "draft" ? "Parsing…" : label.roles.length ? "Re-fill from parser" : "Pre-fill from parser"}
            </button>
          )}

          <label className="flex items-center gap-2">
            <span className="w-20 text-zinc-500">Seniority</span>
            <select
              value={label.seniority ?? ""}
              onChange={(e) => update({ seniority: (e.target.value || null) as Seniority | null })}
              className={`${input} w-40`}
            >
              <option value="">(not sure)</option>
              {LEVELS.map((l) => <option key={l} value={l}>{l}</option>)}
            </select>
          </label>

          <div className="space-y-2">
            <p className="font-medium">Roles <span className="font-normal text-zinc-500">(jobs and internships; dates YYYY-MM, YYYY or present)</span></p>
            {label.roles.map((role, i) => (
              <div key={i} className="grid grid-cols-[1fr_1fr_6rem_6rem_auto] gap-1.5">
                <input aria-label="Title" value={role.title} onChange={(e) => setRole(i, { title: e.target.value })} placeholder="Title" className={input} />
                <input aria-label="Company" value={role.company} onChange={(e) => setRole(i, { company: e.target.value })} placeholder="Company" className={input} />
                <DateInput label="Start" value={role.start} onChange={(v) => setRole(i, { start: v })} />
                <DateInput label="End" value={role.end} onChange={(v) => setRole(i, { end: v })} />
                <button type="button" aria-label="Remove role" onClick={() => update({ roles: label.roles.filter((_, j) => j !== i) })} className="px-2 text-zinc-500 hover:text-red-600">×</button>
              </div>
            ))}
            <button type="button" onClick={() => update({ roles: [...label.roles, { title: "", company: "", start: null, end: null }] })} className="text-emerald-700 hover:underline dark:text-emerald-400">+ Add role</button>
          </div>

          <div className="space-y-2">
            <p className="font-medium">Education</p>
            {label.education.map((school, i) => (
              <div key={i} className="grid grid-cols-[1fr_6rem_1fr_5rem_auto] gap-1.5">
                <input aria-label="Institution" value={school.institution} onChange={(e) => setSchool(i, { institution: e.target.value })} placeholder="Institution" className={input} />
                <input aria-label="Degree" value={school.degree ?? ""} onChange={(e) => setSchool(i, { degree: e.target.value || null })} placeholder="Degree" className={input} />
                <input aria-label="Field" value={school.field ?? ""} onChange={(e) => setSchool(i, { field: e.target.value || null })} placeholder="Field" className={input} />
                <input aria-label="Year" value={school.year ?? ""} onChange={(e) => setSchool(i, { year: e.target.value || null })} placeholder="Year" className={input} />
                <button type="button" aria-label="Remove school" onClick={() => update({ education: label.education.filter((_, j) => j !== i) })} className="px-2 text-zinc-500 hover:text-red-600">×</button>
              </div>
            ))}
            <button type="button" onClick={() => update({ education: [...label.education, { institution: "", degree: null, field: null, year: null }] })} className="text-emerald-700 hover:underline dark:text-emerald-400">+ Add school</button>
          </div>

          <label className="block space-y-1">
            <span className="font-medium">Skills <span className="font-normal text-zinc-500">(comma-separated; every technical skill the resume names)</span></span>
            <textarea value={skillsText} onChange={(e) => setSkillsText(e.target.value)} rows={4} className={input} />
          </label>

          <label className="block space-y-1">
            <span className="font-medium">Notes</span>
            <input value={label.notes} onChange={(e) => update({ notes: e.target.value })} placeholder="Anything unusual about this resume" className={input} />
          </label>

          {!readOnly && (
            <div className="flex flex-wrap items-center gap-2">
              <button type="button" onClick={() => save(false)} className="rounded-md border border-zinc-300 px-3 py-1.5 font-medium hover:bg-zinc-100 dark:border-zinc-700 dark:hover:bg-zinc-800">
                Save draft
              </button>
              <button type="button" onClick={() => save(true)} disabled={badDates} className="rounded-md bg-emerald-600 px-3 py-1.5 font-medium text-white hover:bg-emerald-700 disabled:opacity-50">
                Save as verified
              </button>
              {label.verified && <span className="text-emerald-700 dark:text-emerald-400">✓ verified</span>}
              {badDates && <span className="text-red-700 dark:text-red-400">Fix the dates outlined in red.</span>}
            </div>
          )}
          {message && <p role="status" className="text-zinc-600 dark:text-zinc-400">{message}</p>}
        </fieldset>
      </div>
    </div>
  );
}
